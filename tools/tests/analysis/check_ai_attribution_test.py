"""Behavioral examples for the opt-in attribution prototype."""

import subprocess

import check_ai_attribution as checker
import pytest
from shared.suite import initialize_git_repository, run_git


@pytest.fixture
def repo(tmp_path):
    write(tmp_path, "existing.txt", "old content\n")
    initialize_git_repository(tmp_path, "existing.txt")
    return tmp_path


def write(repo, name, text):
    path = repo / name
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as handle:
        handle.write(text)
    return path


def stage(repo, name, text):
    path = write(repo, name, text)
    run_git(repo, "add", "--", name)
    return path


def commit(repo, message="Update example"):
    run_git(repo, "commit", "-m", message)
    return run_git(repo, "rev-parse", "HEAD").stdout.strip()


