def test_diverged_base_excludes_base_only_history(repo):
    ancestor = run_git(repo, "rev-parse", "HEAD").stdout.strip()
    stage(repo, "base-only.txt", "Author: Codex\n")
    base = commit(repo, "Generated by Codex")
    run_git(repo, "checkout", "-b", "feature", ancestor)
    stage(repo, "feature.txt", "Author: Claude Code\n")
    head = commit(repo)
    assert checker.scan(repo, base, head)[0] == [("feature.txt", 1, "ai-header")]


