def test_partial_staging_reads_index_not_worktree(repo):
    path = stage(repo, "new file é.txt", "\ufeff# Author: Codex\r\n")
    path.write_bytes(b"# Author: Human\n")
    results, skipped = checker.scan(repo)
    assert results == [("new file é.txt", 1, "ai-header")]
    assert skipped == []
    stage(repo, "new file é.txt", "# Author: Human\n")
    path.write_bytes(b"# Author: Codex\n")
    assert checker.scan(repo)[0] == []


def test_only_added_lines_and_rename_changes_are_reported(repo):
    text = "# Author: Claude Code\n" + "unchanged line\n" * 20
    stage(repo, "before.txt", text)
    commit(repo)
    run_git(repo, "mv", "before.txt", "after.txt")
    assert checker.scan(repo)[0] == []
    stage(repo, "after.txt", text + "# Author: Codex\n")
    assert checker.scan(repo)[0] == [("after.txt", 22, "ai-header")]
    run_git(repo, "rm", "-f", "after.txt")
    assert checker.scan(repo)[0] == []


def test_diff_ignores_external_diff_and_textconv(repo):
    stage(repo, "existing.txt", "# Author: Codex\n")
    run_git(repo, "config", "diff.external", "must-not-be-executed")
    stage(repo, ".gitattributes", "*.txt diff=untrusted\n")
    run_git(repo, "config", "diff.untrusted.textconv", "must-not-be-executed")
    assert checker.scan(repo)[0] == [("existing.txt", 1, "ai-header")]


def test_exception_is_exact_and_has_reason(repo):
    stage(repo, "CLAUDE.md", "Author: Claude Code\n")
    stage(repo, "unrelated/CLAUDE.md", "Author: Claude Code\n")
    stage(repo, "resources/external.txt", "Author: Codex\n")
    stage(repo, "localisation/french/example_l_french.yml", "Author: Codex\n")
    stage(repo, "localisation/english/example_l_english.yml", "# Author: Codex\n")
    results, skipped = checker.scan(repo)
    assert {(path, line) for path, line, _ in results} == {
        ("unrelated/CLAUDE.md", 1),
        ("localisation/english/example_l_english.yml", 1),
    }
    assert len(skipped) == 3
    assert all(reason for _, reason in skipped)


def test_binary_and_nontext_are_explicitly_skipped(repo):
    path = stage(repo, "binary.txt", "placeholder")
    path.write_bytes(b"\0# Author: Codex")
    run_git(repo, "add", "binary.txt")
    stage(repo, "image.dds", "# Author: Codex")
    results, skipped = checker.scan(repo)
    assert results == []
    assert len(skipped) == 2
    assert any("binary" in reason for _, reason in skipped)


def test_symlink_is_never_followed(repo):
    blob = run_git(repo, "hash-object", "-w", "existing.txt").stdout.strip()
    run_git(repo, "update-index", "--add", "--cacheinfo", f"120000,{blob},link.txt")
    results, skipped = checker.scan(repo)
    assert results == []
    assert skipped == [("link.txt", "non-regular file (symlink or submodule)")]


