def test_message_file_warns_without_mutation(tmp_path, capsys):
    path = write(
        tmp_path,
        "message",
        "\ufeffFix example\r\n\r\nCo-authored-by: Codex <bot@example.invalid>\r\nCo-authored-by: Human <human@example.invalid>\r\n",
    )
    before = path.read_bytes()
    assert checker.main(["--commit-msg", str(path)]) == 0
    output = capsys.readouterr().out
    assert ":3: ai-trailer:" in output
    assert "1 finding(s)" in output
    assert "human@example" not in output
    assert path.read_bytes() == before


