#!/usr/bin/env python3
# Cross-reference mod overrides against vanilla gameplay and graphics defines.
# Find dead defines, incorrect namespaces, and duplicate overrides.
import difflib
import os
import re
import sys
from pathlib import Path
from typing import Dict, List, Optional, Set, Tuple

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from shared_utils import WORD_BLOCK_START_RE as VANILLA_NAMESPACE_RE
from shared_utils import find_hoi4_install
from validator_common import BaseValidator, run_validator_main

_GRAPHICS_TABLE = "NDefines_Graphics"
_GRAPHICS_PREFIX = f"{_GRAPHICS_TABLE}."
_MD_DEFINES_DIR = Path("common/defines")

MD_DEFINE_RE = re.compile(r"^(NDefines(?:_Graphics)?)\.(?:(\w+)\.)?(\w+)\s*=(?!=)")

# Pattern in vanilla: NAME = value (inside a namespace block)
VANILLA_DEFINE_RE = re.compile(r"^\s+(\w+)\s*=")


def find_vanilla_defines() -> Optional[str]:
    """Auto-detect the vanilla 00_defines.lua path."""
    base = find_hoi4_install()
    if base:
        path = os.path.join(base, "common", "defines", "00_defines.lua")
        if os.path.isfile(path):
            return path
    return None


# Committed fallback for machines without the game (CI), regenerated by
# refresh_vanilla_data.py. Graphics namespaces carry the graphics table prefix.
_DEFINES_MANIFEST = os.path.join(os.path.dirname(__file__), "vanilla_defines.txt")


def load_defines_manifest() -> Dict[str, Set[str]]:
    """Load the qualified namespaces and define names from the manifest."""
    namespaces: Dict[str, Set[str]] = {}
    # UnicodeDecodeError too: decoding happens lazily during iteration, and a
    # corrupt manifest should read as absent (loud setup error), not crash.
    try:
        with open(_DEFINES_MANIFEST, encoding="utf-8") as fh:
            for line in fh:
                line = line.strip()
                if not line or line.startswith("#"):
                    continue
                ns, _, name = line.rpartition(".")
                if ns and name:
                    namespaces.setdefault(ns, set()).add(name)
    except (OSError, UnicodeDecodeError):
        return {}
    return namespaces


def parse_vanilla_defines(filepath: str) -> Dict[str, Set[str]]:
    """Parse a vanilla defines table into {namespace: {define_names}}.

    Vanilla uses nested Lua tables:
        NDefines = {
            NNamespace = {
                DEFINE_NAME = value,
                ...
            },
        }

    Namespace blocks sit at brace depth 1 (inside the top-level NDefines table).
    """
    namespaces: Dict[str, Set[str]] = {}
    current_namespace = None
    brace_depth = 0

    try:
        with open(filepath, "r", encoding="utf-8-sig") as f:
            for line in f:
                stripped = line.strip()

                # Skip pure comment lines
                if stripped.startswith("--"):
                    continue

                # Remove inline comments (naive — ignores strings, but
                # vanilla defines don't embed -- inside string values)
                comment_pos = stripped.find("--")
                if comment_pos >= 0:
                    stripped = stripped[:comment_pos].strip()

                if not stripped:
                    continue

                # Check for namespace opening at depth 1 (inside NDefines)
                ns_match = VANILLA_NAMESPACE_RE.match(stripped)
                if ns_match and brace_depth == 1:
                    ns_name = ns_match.group(1)
                    current_namespace = ns_name
                    namespaces.setdefault(current_namespace, set())

                # Track brace depth (simplified — ignores braces in strings)
                brace_depth += stripped.count("{") - stripped.count("}")

                # Inside a namespace (depth >= 2), collect define names
                if current_namespace and brace_depth >= 2:
                    def_match = VANILLA_DEFINE_RE.match(line)
                    if def_match:
                        name = def_match.group(1)
                        # Skip sub-table names and Lua keywords
                        if name not in (
                            "NDefines",
                            "local",
                            "return",
                            "end",
                            "if",
                            "then",
                            "else",
                            "elseif",
                            "for",
                            "do",
                            "while",
                        ):
                            namespaces[current_namespace].add(name)

                # Namespace closes when we return to depth 1
                if brace_depth <= 1 and current_namespace:
                    current_namespace = None

    except Exception as e:
        print(f"Error reading vanilla defines: {e}", file=sys.stderr)

    return namespaces


def parse_vanilla_define_files(
    filepath: str, *, require_graphics: bool = True
) -> Dict[str, Set[str]]:
    """Read gameplay defines and the sibling graphics file."""
    vanilla = parse_vanilla_defines(filepath)
    if not vanilla:
        return {}
    graphics_path = os.path.join(os.path.dirname(filepath), "00_graphics.lua")
    if require_graphics or os.path.exists(graphics_path):
        graphics = parse_vanilla_defines(graphics_path)
        if not graphics:
            return {}
        vanilla.update(
            {f"{_GRAPHICS_PREFIX}{ns}": names for ns, names in graphics.items()}
        )
    return vanilla


def parse_md_defines(filepath: str) -> List[Tuple[str, Optional[str], str, int]]:
    """Read flat overrides as (table, namespace, name, line number)."""
    results = []
    try:
        with open(filepath, "r", encoding="utf-8-sig") as f:
            for line_num, line in enumerate(f, start=1):
                clean = line.partition("--")[0].strip()
                match = MD_DEFINE_RE.match(clean)
                if match:
                    table, namespace, name = match.groups()
                    results.append((table, namespace, name, line_num))
    except (OSError, UnicodeDecodeError) as e:
        print(f"Error reading MD defines: {e}", file=sys.stderr)

    return results


class Validator(BaseValidator):
    TITLE = "DEFINES VALIDATION"
    STAGED_EXTENSIONS = [".lua"]

    def __init__(self, *args, vanilla_path: Optional[str] = None, **kwargs):
        super().__init__(*args, **kwargs)
        self.vanilla_path = vanilla_path

    def run_validations(self):
        self._validate_defines()

    def _validate_defines(self):
        defines_dir = Path(self.mod_path) / _MD_DEFINES_DIR
        paths = sorted(defines_dir.glob("*.lua"))
        if self.staged_only and self.staged_files:
            staged = {Path(path).resolve() for path in self.staged_files}
            paths = [path for path in paths if path.resolve() in staged]
            if not paths:
                self.log("  No mod defines staged, skipping")
                return

        if not paths:
            self.add_error(
                "defines-setup", f"No Lua defines files found in {defines_dir}"
            )
            return

        if self.vanilla_path and not os.path.isfile(self.vanilla_path):
            self.add_error(
                "defines-setup",
                f"--vanilla-path {self.vanilla_path} does not exist",
            )
            return

        vanilla_path = self.vanilla_path or find_vanilla_defines()
        vanilla = (
            parse_vanilla_define_files(
                vanilla_path, require_graphics=not self.vanilla_path
            )
            if vanilla_path
            else load_defines_manifest()
        )
        if not vanilla:
            self.add_error(
                "defines-setup",
                "Cannot load vanilla 00_defines.lua and 00_graphics.lua or a "
                "vanilla_defines.txt manifest. Set --vanilla-path, install HOI4 via "
                "Steam, or run refresh_vanilla_data.py on a machine with the game.",
            )
            return

        self.log(f"  Vanilla defines: {vanilla_path or 'vanilla_defines.txt manifest'}")
        graphics_namespaces = {
            ns.removeprefix(_GRAPHICS_PREFIX): names
            for ns, names in vanilla.items()
            if ns.startswith(_GRAPHICS_PREFIX)
        }
        # Vanilla copies each graphics namespace to NDefines by reference.
        vanilla_namespaces = {
            ns: names
            for ns, names in vanilla.items()
            if not ns.startswith(_GRAPHICS_PREFIX)
        }
        vanilla_namespaces.update(graphics_namespaces)
        all_vanilla_names: Dict[str, List[str]] = {}
        for ns, names in vanilla_namespaces.items():
            for name in sorted(names):
                all_vanilla_names.setdefault(name, []).append(ns)

        dead_results = []
        namespace_results = []
        duplicate_results = []
        seen: Dict[Tuple[str, str], Tuple[str, int]] = {}
        for path in paths:
            rel_path = (_MD_DEFINES_DIR / path.name).as_posix()
            for table, namespace, name, line_num in parse_md_defines(str(path)):
                if namespace is None:
                    message = f"{table}.{name} is missing a namespace"
                    namespace_results.append((message, rel_path, line_num))
                    continue

                key = f"{namespace}.{name}"
                valid_namespaces = (
                    graphics_namespaces
                    if table == _GRAPHICS_TABLE
                    else vanilla_namespaces
                )
                if name not in all_vanilla_names:
                    matches = difflib.get_close_matches(
                        name, all_vanilla_names, n=1, cutoff=0.7
                    )
                    suggestion = ""
                    if matches:
                        correct_ns = all_vanilla_names[matches[0]][0]
                        suggestion = f" (did you mean '{matches[0]}' in {correct_ns}?)"
                    message = f"{key} does not exist in vanilla{suggestion}"
                    dead_results.append((message, rel_path, line_num))
                elif name not in valid_namespaces.get(namespace, ()):
                    correct_namespaces = ", ".join(all_vanilla_names[name])
                    message = (
                        f"{table}.{key} — wrong namespace or table, "
                        f"vanilla has it in {correct_namespaces}"
                    )
                    namespace_results.append((message, rel_path, line_num))

                pair = (namespace, name)
                if pair in seen:
                    prev_path, prev_line = seen[pair]
                    location = (
                        f"line {prev_line}"
                        if prev_path == rel_path
                        else f"{prev_path}:{prev_line}"
                    )
                    message = f"duplicate {key} (first defined at {location})"
                    duplicate_results.append((message, rel_path, line_num))
                else:
                    seen[pair] = (rel_path, line_num)

        self._report(
            dead_results,
            "✓ All MD defines exist in vanilla",
            "Dead or fabricated defines (silently ignored by the game):",
        )
        self._report(
            namespace_results,
            "✓ All MD defines use correct namespaces",
            "Defines in wrong namespace (silently ignored by the game):",
        )
        self._report(
            duplicate_results,
            "✓ No duplicate defines found",
            "Duplicate defines (last value wins silently):",
        )


if __name__ == "__main__":

    def extra_args(parser):
        parser.add_argument(
            "--vanilla-path",
            type=str,
            default=None,
            help=(
                "Path to vanilla 00_defines.lua. Loads 00_graphics.lua from the "
                "same directory if present. Auto-detects Steam if omitted."
            ),
        )

    run_validator_main(
        Validator, "Validate MD defines against vanilla HOI4", extra_args_fn=extra_args
    )
