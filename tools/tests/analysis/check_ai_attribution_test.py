def test_branch_scans_new_messages_and_diff_but_not_base_history(repo):
    stage(repo, "legacy.txt", "# Author: Claude Code\n")
    base = commit(repo, "Legacy\n\nCo-authored-by: Codex <bot@example.invalid>")
    stage(repo, "new.txt", "safe\n# Author: Codex\n")
    head = commit(
        repo,
        "New\n\nGenerated with Claude Code\nCo-authored-by: Human <human@example.invalid>",
    )
    results, skipped = checker.scan(repo, base, head)
    assert results == [
        (f"commit {head[:12]}", 3, "ai-footer"),
        ("new.txt", 2, "ai-header"),
    ]
    assert skipped == []
    assert checker.scan(repo, head, head) == ([], [])


