def test_safe_diagnostics_and_git_errors(repo, capsys, monkeypatch):
    stage(repo, "example.txt", "Generated with Claude Code\n")
    assert checker.main(["--staged", "--repo", str(repo)]) == 0
    assert 'WARNING "example.txt":1: ai-footer:' in capsys.readouterr().out

    def timeout(*_args, **_kwargs):
        raise subprocess.TimeoutExpired("git", 30)

    monkeypatch.setattr(checker.subprocess, "run", timeout)
    assert checker.main(["--staged", "--repo", str(repo)]) == 2
    assert "incomplete" in capsys.readouterr().err


