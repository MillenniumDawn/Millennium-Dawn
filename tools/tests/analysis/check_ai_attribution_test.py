def test_conflicted_index_is_incomplete(repo):
    base = run_git(repo, "rev-parse", "HEAD").stdout.strip()
    stage(repo, "existing.txt", "left\n")
    left = commit(repo)
    run_git(repo, "checkout", "-b", "right", base)
    stage(repo, "existing.txt", "right\n")
    commit(repo)
    with pytest.raises(subprocess.CalledProcessError):
        run_git(repo, "merge", left)
    with pytest.raises(checker.ScanError, match="unmerged"):
        checker.scan(repo)


